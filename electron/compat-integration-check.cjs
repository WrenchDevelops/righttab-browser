// Exercises the actual browser initialization using a disposable profile.
const { app } = require('electron');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const root = process.argv[2];
if (!root) throw new Error('A disposable profile is required.');
process.env.RIGHTTAB_EXTENSION_TEST = '1';
app.setPath('userData', root);
app.whenReady().then(async () => {
  const source = path.join(root, 'Extensions', 'compat-probe-12345'); fs.mkdirSync(source, { recursive: true });
  fs.writeFileSync(path.join(source, 'manifest.json'), JSON.stringify({ name: 'Compat probe', version: '1.0', manifest_version: 3, permissions: ['tabs'], background: { service_worker: 'worker.js' } }));
  fs.writeFileSync(path.join(source, 'worker.js'), `
    console.log('DEBUGGER_DISABLED', typeof chrome.debugger === 'undefined');
    const onFocus = () => { chrome.windows.onFocusChanged.removeListener(onFocus); console.log('FOCUS_REMOVED', !chrome.windows.onFocusChanged.hasListeners()); };
    chrome.windows.onFocusChanged.addListener(onFocus);
    chrome.tabs.insertCSS(987654321, { code: 'body {}' }).then(() => console.log('UNSUPPORTED_BAD'), e => console.log('UNSUPPORTED_REJECTED', /Unsupported/.test(e.message)));
    chrome.windows.get(987654321).then(() => console.log('WIN_BAD'), e => console.log('WIN_REJECTED', /No window/.test(e.message)));
    chrome.windows.get(987654321, () => console.log('WIN_CALLBACK_ERROR', !!chrome.runtime.lastError, /No window/.test(chrome.runtime.lastError?.message || '')));
    chrome.tabs.get(987654321).then(() => console.log('PROMISE_BAD'), e => console.log('PROMISE_REJECTED', /No tab/.test(e.message)));
    chrome.tabs.get(987654321, () => { console.log('CALLBACK_ERROR', !!chrome.runtime.lastError, /No tab/.test(chrome.runtime.lastError?.message || '')); queueMicrotask(() => console.log('CALLBACK_CLEARED', chrome.runtime.lastError === undefined)); });
  `);
  const unprivileged = path.join(root, 'Extensions', 'compat-no-permission'); fs.mkdirSync(unprivileged);
  fs.writeFileSync(path.join(unprivileged, 'manifest.json'), JSON.stringify({ name: 'Permission probe', version: '1.0', manifest_version: 3, background: { service_worker: 'worker.js' } }));
  fs.writeFileSync(path.join(unprivileged, 'worker.js'), `chrome.tabs.get(123).then(() => console.log('DENIAL_BAD'), e => console.log('DENIAL_OK', /permission/.test(e.message)));`);
  fs.writeFileSync(path.join(root, 'settings.json'), JSON.stringify({ completedSetup: true, importOffered: true, installedExtensions: [{ installId: 'compat-probe-12345', name: 'Compat probe', version: '1.0', path: source, enabled: true }, { installId: 'compat-no-permission', name: 'Permission probe', version: '1.0', path: unprivileged, enabled: true }] }));
  const seen = [];
  require('electron').session.fromPartition('persist:righttab').serviceWorkers.on('console-message', (_event, d) => { if (/^(PROMISE_|CALLBACK_|UNSUPPORTED_|FOCUS_|WIN_|DENIAL_|DEBUGGER_)/.test(d.message)) seen.push(d.message); });
  const browser = require('./browser.cjs').startBrowser();
  await browser.ready;
  const win = await browser.whenWindow();
  const original = win.activeTabId;
  const created = browser.createTab(win, { url: 'https://example.com/', background: true });
  assert.equal(win.activeTabId, original, 'background tab unexpectedly selected');
  browser.selectTab(win, created.id);
  assert.equal(browser.extensionCompat.ctx.store.getActiveTabFromWindow(win.win), created.view.webContents);
  const primary = win.activeTabId;
  browser.openSplit(win, { tabId: original });
  assert.equal(browser.activeContents(win), win.tabs.get(original).view.webContents);
  assert.equal(browser.extensionCompat.ctx.store.getActiveTabFromWindow(win.win), win.tabs.get(original).view.webContents, 'focused split pane was not exposed as the active extension tab');
  browser.closeSplit(win);
  assert.equal(browser.extensionCompat.ctx.store.getActiveTabFromWindow(win.win), win.tabs.get(primary).view.webContents, 'primary pane was not restored as the active extension tab');
  browser.closeTab(win, created.id);
  assert.ok(browser.extensionCompat, 'test-session adapter not initialized');
  assert.equal(browser.extensionCompat.ctx.store.tabs.size, 1);
  const result = browser.store.settings.installedExtensions.find((record) => record.installId === 'compat-probe-12345');
  assert.ok(result?.chromiumId, 'probe was not restored');
  for (let i = 0; i < 150 && seen.length < 8; i++) await new Promise((r) => setTimeout(r, 50));
  assert.ok((browser.extensionCompat.ctx.router.listeners.get('windows.onFocusChanged') || []).some((l) => l.extensionId === result.chromiumId));
  assert.ok(seen.includes('PROMISE_REJECTED true'), JSON.stringify(seen));
  assert.ok(seen.includes('CALLBACK_ERROR true true'), JSON.stringify(seen));
  assert.ok(seen.includes('UNSUPPORTED_REJECTED true'), JSON.stringify(seen));
  assert.ok(seen.includes('WIN_REJECTED true'), JSON.stringify(seen));
  assert.ok(seen.includes('WIN_CALLBACK_ERROR true true'), JSON.stringify(seen));
  assert.ok(seen.includes('DENIAL_OK true'), JSON.stringify(seen));
  assert.ok(seen.includes('CALLBACK_CLEARED true'), JSON.stringify(seen));
  assert.ok(seen.includes('DEBUGGER_DISABLED true'), JSON.stringify(seen));
  browser.extensionCompat.api.windows.onFocusChanged(-1);
  for (let i = 0; i < 100 && !seen.includes('FOCUS_REMOVED true'); i++) await new Promise((r) => setTimeout(r, 50));
  assert.ok(seen.includes('FOCUS_REMOVED true'), JSON.stringify(seen));
  console.log('PASS actual app initialization, window event, tab registration, promise and callback errors');
  app.exit(0);
}).catch((error) => { console.error(error); app.exit(1); });
